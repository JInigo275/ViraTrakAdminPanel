-- Allow the app to save driver IDs in YYMMDDNN format.
-- Run this once in the Supabase SQL Editor before creating new drivers.

BEGIN;

DO $$
DECLARE
  identity_kind "char";
BEGIN
  SELECT attidentity
    INTO identity_kind
    FROM pg_attribute
   WHERE attrelid = 'public.driver'::regclass
     AND attname = 'driver_id'
     AND NOT attisdropped;

  IF identity_kind = 'a' THEN
    ALTER TABLE public.driver
      ALTER COLUMN driver_id SET GENERATED BY DEFAULT;
  END IF;
END;
$$;

COMMIT;