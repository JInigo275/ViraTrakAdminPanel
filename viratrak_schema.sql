-- ============================================================
-- Legacy ERD tables
-- Kept so you can preserve the original model while also matching the app.
-- These are not currently used by the frontend, but they are safe to keep.
-- ============================================================

CREATE TABLE IF NOT EXISTS driver (
    driver_id       INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    first_name      VARCHAR(50) NOT NULL,
    last_name       VARCHAR(25) NOT NULL,
    license_number  VARCHAR(20) NOT NULL UNIQUE,
    contact_info    VARCHAR(15)
);

CREATE TABLE IF NOT EXISTS vehicle (
    vehicle_id    INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    plate_number  VARCHAR(10) NOT NULL UNIQUE,
    model         VARCHAR(50),
    driver_id     INT REFERENCES driver(driver_id)
);

CREATE TABLE IF NOT EXISTS device (
    device_id   INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    status      VARCHAR(10),
    video_feed  VARCHAR(255),
    vehicle_id  INT REFERENCES vehicle(vehicle_id)
);

CREATE TABLE IF NOT EXISTS recorded_evidence (
    event_id   INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    timestamp  TIMESTAMP NOT NULL DEFAULT now(),
    device_id  INT REFERENCES device(device_id)
);

CREATE TABLE IF NOT EXISTS detection (
    detection_id    INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    timestamp       TIMESTAMP NOT NULL DEFAULT now(),
    perclos         DOUBLE PRECISION,
    blink_rate      DOUBLE PRECISION,
    yawn            DOUBLE PRECISION,
    body_posture    DOUBLE PRECISION,
    head_pose       DOUBLE PRECISION,
    fatigue_score   DOUBLE PRECISION,
    driver_state    VARCHAR(10),
    event_id        INT REFERENCES recorded_evidence(event_id)
);

CREATE TABLE IF NOT EXISTS alert (
    alert_id      INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    alert_level   VARCHAR(10),
    alert_type    VARCHAR(10),
    duration      TIME,
    detection_id  INT REFERENCES detection(detection_id)
);

CREATE TABLE IF NOT EXISTS device_action (
    action_id    INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    action_type  VARCHAR(10),
    duration     TIME,
    timestamp    TIMESTAMP NOT NULL DEFAULT now(),
    device_id    INT REFERENCES device(device_id),
    alert_id     INT REFERENCES alert(alert_id)
);

CREATE TABLE IF NOT EXISTS behavior_log (
    log_id        INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    message       VARCHAR(255),
    timestamp     TIMESTAMP NOT NULL DEFAULT now(),
    date          DATE NOT NULL DEFAULT CURRENT_DATE,
    alert_id      INT REFERENCES alert(alert_id),
    device_id     INT REFERENCES device(device_id),
    vehicle_id    INT REFERENCES vehicle(vehicle_id),
    detection_id  INT REFERENCES detection(detection_id),
    event_id      INT REFERENCES recorded_evidence(event_id)
);

CREATE TABLE IF NOT EXISTS system_log (
    systemlog_id  INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    message       VARCHAR(255),
    log_type      VARCHAR(10),
    timestamp     TIMESTAMP NOT NULL DEFAULT now(),
    device_id     INT REFERENCES device(device_id)
);

CREATE INDEX IF NOT EXISTS idx_vehicle_driver_id ON vehicle(driver_id);
CREATE INDEX IF NOT EXISTS idx_device_vehicle_id ON device(vehicle_id);
CREATE INDEX IF NOT EXISTS idx_recorded_evidence_device_id ON recorded_evidence(device_id);
CREATE INDEX IF NOT EXISTS idx_detection_event_id ON detection(event_id);
CREATE INDEX IF NOT EXISTS idx_alert_detection_id ON alert(detection_id);
CREATE INDEX IF NOT EXISTS idx_device_action_device_id ON device_action(device_id);
CREATE INDEX IF NOT EXISTS idx_device_action_alert_id ON device_action(alert_id);
CREATE INDEX IF NOT EXISTS idx_behavior_log_alert_id ON behavior_log(alert_id);
CREATE INDEX IF NOT EXISTS idx_behavior_log_device_id ON behavior_log(device_id);
CREATE INDEX IF NOT EXISTS idx_behavior_log_vehicle_id ON behavior_log(vehicle_id);
CREATE INDEX IF NOT EXISTS idx_behavior_log_detection_id ON behavior_log(detection_id);
CREATE INDEX IF NOT EXISTS idx_behavior_log_event_id ON behavior_log(event_id);
CREATE INDEX IF NOT EXISTS idx_system_log_device_id ON system_log(device_id);

