-- ============================================================
-- ViraTrak App Schema for Supabase
-- Matches the data shapes used by the frontend:
-- - usersApi  -> users
-- - driversApi -> drivers
-- - alertsApi -> alerts
-- - logsApi   -> logs
-- ============================================================

-- ============================================================
-- 1. USERS
-- ============================================================
CREATE TABLE IF NOT EXISTS users (
    id                   TEXT PRIMARY KEY,
    first_name           TEXT NOT NULL,
    last_name            TEXT NOT NULL,
    email                TEXT NOT NULL UNIQUE,
    role                 TEXT NOT NULL CHECK (role IN ('Owner', 'Administrator', 'Supervisor')),
    status               TEXT NOT NULL CHECK (status IN ('Active', 'Inactive')),
    last_login           TEXT NOT NULL DEFAULT 'Never',
    password             TEXT NOT NULL,
    must_change_password BOOLEAN NOT NULL DEFAULT FALSE,
    avatar               TEXT,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================
-- 2. DRIVERS
-- ============================================================
CREATE TABLE IF NOT EXISTS drivers (
    id           TEXT PRIMARY KEY,
    first_name   TEXT NOT NULL,
    last_name    TEXT NOT NULL,
    vehicle      TEXT NOT NULL,
    contact      TEXT NOT NULL,
    safety_score INTEGER NOT NULL CHECK (safety_score BETWEEN 0 AND 100),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================
-- 3. ALERTS
-- ============================================================
CREATE TABLE IF NOT EXISTS alerts (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type       TEXT NOT NULL,
    driver     TEXT NOT NULL,
    vehicle    TEXT NOT NULL,
    date       TEXT NOT NULL,
    time       TEXT NOT NULL,
    severity   TEXT NOT NULL CHECK (severity IN ('High', 'Moderate', 'Low')),
    evidence   BOOLEAN NOT NULL DEFAULT FALSE,
    icon_color TEXT NOT NULL,
    icon_bg    TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================
-- 4. SYSTEM LOGS
-- ============================================================
CREATE TABLE IF NOT EXISTS logs (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source     TEXT NOT NULL CHECK (source IN ('System', 'Hardware')),
    date       TEXT NOT NULL,
    time       TEXT NOT NULL,
    level      TEXT NOT NULL CHECK (level IN ('INFO', 'WARNING', 'ERROR')),
    ref        TEXT NOT NULL,
    action     TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================
-- Indexes for common lookups
-- ============================================================
CREATE INDEX IF NOT EXISTS idx_users_email ON users(email);
CREATE INDEX IF NOT EXISTS idx_users_role ON users(role);
CREATE INDEX IF NOT EXISTS idx_drivers_vehicle ON drivers(vehicle);
CREATE INDEX IF NOT EXISTS idx_alerts_type ON alerts(type);
CREATE INDEX IF NOT EXISTS idx_alerts_driver ON alerts(driver);
CREATE INDEX IF NOT EXISTS idx_alerts_vehicle ON alerts(vehicle);
CREATE INDEX IF NOT EXISTS idx_alerts_severity ON alerts(severity);
CREATE INDEX IF NOT EXISTS idx_logs_source ON logs(source);
CREATE INDEX IF NOT EXISTS idx_logs_level ON logs(level);

